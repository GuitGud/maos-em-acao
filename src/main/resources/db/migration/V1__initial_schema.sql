create table campaigns (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    name varchar(255) not null,
    description varchar(2000) not null,
    status varchar(255) not null
);

create table items (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    name varchar(255) not null,
    unit varchar(255) not null,
    balance integer not null,
    unique(name),
    check (balance >= 0)
);

create table volunteers (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    name varchar(255) not null,
    email varchar(255) not null,
    password_hash varchar(255) not null,
    approved boolean not null,
    role varchar(255) not null,
    unique(email)
);

create table needs (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    campaign_id bigint not null references campaigns(id),
    item_id bigint not null references items(id),
    target integer not null,
    unique(campaign_id, item_id),
    check (target > 0)
);

create table shifts (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    campaign_id bigint not null references campaigns(id),
    title varchar(255) not null,
    starts_at timestamp(6) not null,
    ends_at timestamp(6) not null,
    capacity integer not null,
    status varchar(255) not null,
    check (capacity > 0),
    check (ends_at > starts_at)
);

create table registrations (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    shift_id bigint not null references shifts(id),
    volunteer_id bigint not null references volunteers(id),
    status varchar(255) not null,
    hours double precision not null,
    unique(shift_id, volunteer_id),
    check (hours >= 0)
);

create table movements (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    item_id bigint not null references items(id),
    campaign_id bigint not null references campaigns(id),
    quantity integer not null,
    kind varchar(255) not null,
    reason varchar(2000) not null,
    created_at timestamp(6) not null,
    actor_id bigint not null references volunteers(id)
);

create table deliverys (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    campaign_id bigint not null references campaigns(id),
    item_id bigint not null references items(id),
    quantity integer not null,
    beneficiary varchar(255) not null,
    vulnerability integer not null,
    members integer not null,
    priority integer not null,
    status varchar(255) not null,
    created_at timestamp(6) not null,
    actor_id bigint not null references volunteers(id),
    reason varchar(2000) not null,
    check (quantity > 0),
    check (members > 0),
    check (vulnerability between 1 and 5)
);

create table notifications (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    volunteer_id bigint not null references volunteers(id),
    message varchar(2000) not null,
    seen boolean not null,
    created_at timestamp(6) not null
);

create table feedbacks (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    registration_id bigint not null references registrations(id),
    rating integer not null,
    comment varchar(2000) not null,
    unique(registration_id),
    check (rating between 1 and 5)
);

create table reports (
    id bigint generated by default as identity primary key,
    version bigint not null default 0,
    title varchar(255) not null,
    content varchar(12000) not null,
    created_at timestamp(6) not null,
    actor_id bigint not null references volunteers(id)
);

create index ix_notifications_owner on notifications(volunteer_id);
create index ix_shifts_campaign on shifts(campaign_id);
create index ix_movements_item on movements(item_id);
